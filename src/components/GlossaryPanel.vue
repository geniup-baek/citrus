    ],
  },
]

const query = ref('')

function matches(term) {
  const q = query.value.trim().toLowerCase()
  if (!q) return true
  return term.term.toLowerCase().includes(q) || term.def.toLowerCase().includes(q)
}

const filteredGroups = computed(() =>
  glossaryGroups
    .map((group) => ({ ...group, terms: group.terms.filter(matches) }))
    .filter((group) => group.terms.length > 0),
)

const totalCount = glossaryGroups.reduce((sum, g) => sum + g.terms.length, 0)
const visibleCount = computed(() => filteredGroups.value.reduce((sum, g) => sum + g.terms.length, 0))
</script>

