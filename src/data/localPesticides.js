export function findByBrandName(name) {
  return LOCAL_PESTICIDES.find(p => p.brandName === name) ?? null
}

export function getUniquePests() {
  const set = new Set()
  for (const p of LOCAL_PESTICIDES) {
    for (const pest of p.targetPests) {
      set.add(pest.replace(/\(.*?\)/g, '').trim())
    }
  }
  return [...set].sort((a, b) => a.localeCompare(b, 'ko'))
}

export function matchesPest(pesticide, term) {
  if (!term) return true
  const t = term.trim()
  return pesticide.targetPests.some(p => {
    const base = p.replace(/\(.*?\)/g, '').trim()
    return base.includes(t) || t.includes(base)
  })
}
